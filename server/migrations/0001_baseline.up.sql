-- 0001 baseline: the schema AI Prism 1.4 built at boot (runSchemaDdl in
-- server/db.js before versioned migrations), statement for statement and in
-- the same order, so an empty database ends up with exactly the tables,
-- columns (and column order), defaults, constraints and indexes it had.
--
-- Every statement is idempotent (IF NOT EXISTS, guarded DO blocks), on
-- purpose: a database created by an OLDER 1.x boot is upgraded by running this
-- file as-is. A database whose newest 1.4 artifact already exists is not
-- touched at all: the runner records version 1 for it without running this
-- file (see adoptProbeEra in server/db/migrate.js).
--
-- Do not edit this file once released: the runner refuses an applied
-- migration whose checksum changed. Schema changes go in a new
-- server/migrations/NNNN_<name>.{up,down}.sql.
--
-- ai_prism.pgvector (transaction-local, set by the runner): 'off' only for
-- LOCAL_DEV_MODE=1 without LOCAL_PGVECTOR=1 (Homebrew Postgres without the
-- pgvector extension); everything else, including Lakebase, gets 'on'.

